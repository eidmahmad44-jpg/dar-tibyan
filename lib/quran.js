const TOTAL_AYAHS = SURAHS.reduce((s, x) => s + x.ayahs, 0);

/** دمج مجالات الآيات [from,to] (شاملة) داخل السورة الواحدة. */
function mergeRanges(ranges) {
  const r = ranges.map(([a, b]) => [Math.min(a, b), Math.max(a, b)]).sort((x, y) => x[0] - y[0]);
  const out = [];
  for (const [a, b] of r) {
    const last = out[out.length - 1];
    if (last && a <= last[1] + 1) last[1] = Math.max(last[1], b);
    else out.push([a, b]);
  }
  return out;
}

/**
 * entries: [{surah, from, to}] → { total, percent, perSurah: {n: count} }
 * يحسب الآيات المحفوظة المسجّلة (اتحاد المجالات، بلا تكرار).
 */
function coverage(entries) {
  const by = {};
  for (const e of entries) {
    const s = SURAHS[e.surah - 1];
    if (!s) continue;
    const from = Math.max(1, Math.min(s.ayahs, e.from | 0));
    const to = Math.max(1, Math.min(s.ayahs, e.to | 0));
    (by[e.surah] = by[e.surah] || []).push([from, to]);
  }
  const perSurah = {};
  let total = 0;
  for (const k of Object.keys(by)) {
    const merged = mergeRanges(by[k]);
    const c = merged.reduce((s, [a, b]) => s + (b - a + 1), 0);
    perSurah[k] = c;
    total += c;
  }
  return { total, percent: Math.round((total / TOTAL_AYAHS) * 1000) / 10, perSurah };
}

